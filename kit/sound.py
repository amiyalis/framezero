"""
sound.py — a royalty-free soundtrack synthesizer. Every sound is generated by code (numpy + scipy),
so there is nothing to license and nothing that gets muted for copyright.

    import sys; sys.path.insert(0, 'kit'); from sound import *
    music, fx = Mix(12), Mix(12)
    lofi_keys(music, 0, 12); lofi_beat(music, 0, 12)          # a whole lo-fi bed in two lines
    fx.add(impact(), 0.0); fx.add(pop(900), 1.5, 0.7)         # effects synced to the scene timeline
    Mix.save(Mix.blend([(music, 1.0), (fx, 0.9)], 12).master(12, 0.70), 'soundtrack.wav')

Times are in seconds and must match the scene's timeline exactly (same numbers as in seek(t)).
"""
import wave

import numpy as np
from scipy.signal import butter, sosfilt

SR = 48000
rng = np.random.default_rng(7)  # fixed seed = the same soundtrack every run


# ---------------- basics ----------------
def t_(d):
    return np.arange(int(d * SR)) / SR


def lp(x, f, o=2):
    return sosfilt(butter(o, f, 'low', fs=SR, output='sos'), x)


def hp(x, f, o=2):
    return sosfilt(butter(o, f, 'high', fs=SR, output='sos'), x)


def bp(x, a, b, o=2):
    return sosfilt(butter(o, [a, b], 'band', fs=SR, output='sos'), x)


def note(n):
    """Frequency of a note n semitones away from A4 (440 Hz). note(3) = C5, note(-9) = C4."""
    return 440.0 * 2 ** (n / 12)


def saw(f, t):
    return 2 * ((f * t) % 1.0) - 1


# ---------------- drums (energetic, ~120 BPM) ----------------
def kick(d=0.45, f0=160, f1=42, punch=1.0):
    t = t_(d)
    f = f1 + (f0 - f1) * np.exp(-t * 28)
    x = np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t * 7.5)
    click_ = hp(rng.standard_normal(len(t)), 2500) * np.exp(-t * 300) * 0.25 * punch
    return np.tanh((x + click_) * 1.6) * 0.95


def clap(d=0.35):
    t = t_(d)
    e = np.zeros_like(t)
    for off in (0, .011, .022):
        m = t >= off
        e[m] += np.exp(-(t[m] - off) * (55 if off < .02 else 16))
    return bp(rng.standard_normal(len(t)), 900, 5200) * e * 0.55


def hat(d=0.07, open_=False):
    t = t_(0.28 if open_ else d)
    return hp(rng.standard_normal(len(t)), 7500, 4) * np.exp(-t * (14 if open_ else 75)) * 0.22


# ---------------- synths ----------------
def bass(f, d):
    t = t_(d)
    x = lp(np.sin(2 * np.pi * f * t) * 0.8 + saw(f, t) * 0.25, 520)
    a = np.minimum(1, t / 0.008) * np.exp(-t * 3.2)
    return np.tanh(x * a * 1.8) * 0.55


def pad(freqs, d):
    """Wide detuned saw pad (stereo)."""
    t = t_(d)
    L = np.zeros_like(t); R = np.zeros_like(t)
    for f in freqs:
        for det, side in ((-0.11, 'L'), (0.0, 'C'), (0.12, 'R')):
            v = saw(f * 2 ** (det / 12), t)
            if side in 'LC': L += v
            if side in 'RC': R += v
    a = np.minimum(1, t / 0.25) * np.minimum(1, (d - t) / 0.3).clip(0, 1)
    k = 0.045 / max(1, len(freqs))
    return np.stack([lp(L, 1600) * a, lp(R, 1600) * a]) * k * 3


def pluck(f, d=0.35):
    t = t_(d)
    x = saw(f, t) * 0.6 + np.sin(2 * np.pi * f * 2 * t) * 0.3
    return lp(x, 3800) * np.exp(-t * 9) * np.minimum(1, t / 0.003) * 0.28


# ---------------- lo-fi instruments (calm, swung, vinyl) ----------------
def rhodes(f, d):
    """Electric-piano tone with tape wobble and tremolo."""
    t = t_(d + 0.25)
    vib = 1 + 0.0025 * np.sin(2 * np.pi * 0.7 * t)
    ph = 2 * np.pi * f * np.cumsum(vib) / SR
    x = np.sin(ph) + 0.32 * np.sin(2 * ph) * np.exp(-t * 2.5) + 0.07 * np.sin(3 * ph) * np.exp(-t * 6)
    x += 0.12 * np.sin(2 * np.pi * f * 7.02 * t) * np.exp(-t * 28)  # the "tine"
    env = np.minimum(1, t / 0.01) * np.exp(-t * 0.9)
    rel = np.ones_like(t); n = int(0.25 * SR); rel[-n:] = np.linspace(1, 0, n) ** 2
    return x * env * rel * (1 + 0.12 * np.sin(2 * np.pi * 3.0 * t)) * 0.16


def chord(notes, d, g=1.0):
    """Softly strummed rhodes chord; notes in semitones from A4."""
    out = np.zeros(int((d + 0.4) * SR))
    for i, n in enumerate(notes):
        y = rhodes(note(n), d); o = int(i * 0.022 * SR)
        m = min(len(y), len(out) - o); out[o:o + m] += y[:m]
    return lp(out, 3200) * g


def sub(f, d):
    t = t_(d)
    env = np.minimum(1, t / 0.03) * np.exp(-t * 1.2)
    rel = np.ones_like(t); n = int(0.08 * SR); rel[-n:] = np.linspace(1, 0, n)
    return (np.sin(2 * np.pi * f * t) + 0.15 * np.sin(4 * np.pi * f * t)) * env * rel * 0.42


def bell(f, d=1.2):
    t = t_(d)
    x = np.sin(2 * np.pi * f * t) + 0.25 * np.sin(2 * np.pi * f * 2.01 * t) * np.exp(-t * 4)
    return lp(x * np.exp(-t * 2.6) * np.minimum(1, t / 0.004), 4000) * 0.11


def lofi_kick():
    return lp(kick(0.38, 115, 44, 0.25), 1100) * 0.85


def snare():
    t = t_(0.28)
    n = bp(rng.standard_normal(len(t)), 300, 3800) * np.exp(-t * 20) * 0.32
    return lp(n + np.sin(2 * np.pi * 185 * t) * np.exp(-t * 28) * 0.28, 5200)


def soft_hat(g=1.0):
    t = t_(0.06)
    return lp(hp(rng.standard_normal(len(t)), 6000, 2), 9500) * np.exp(-t * 85) * 0.11 * g


def vinyl(d):
    """Vinyl hiss + random crackles."""
    n = int(d * SR)
    x = lp(hp(rng.standard_normal(n), 900), 5500) * 0.010
    for _ in range(int(d * 7)):
        i = rng.integers(0, n - 200); a = rng.uniform(0.04, 0.22) * (1 if rng.random() < .5 else -1)
        x[i:i + 40] += a * np.exp(-np.arange(40) / 6)
    return x


# Em9 – Cmaj9 – Am9 – Bm7, one chord every 2 s (= one bar at 120 BPM)
LOFI_CHORDS = [[-14, -10, -7, -3], [-14, -10, -7, -5], [-14, -10, -9, -5], [-12, -10, -7, -3]]
LOFI_BASS = [-29, -33, -24, -26]


def lofi_keys(mix, a, b, g=1.0, bar=2.0):
    """Lay rhodes chords + sub bass from a to b seconds."""
    t = a
    while t < b - 1e-6:
        c = int(t // bar) % 4; end = min(b, (int(t // bar) + 1) * bar)
        mix.add(chord(LOFI_CHORDS[c], end - t, g), t, 1.0)
        mix.add(sub(note(LOFI_BASS[c]), end - t), t, 0.9 * g)
        t = end


def lofi_beat(mix, a, b, g=1.0, bar=2.0, swing=0.055):
    """Half-time swung beat: kick on 1 and the 'and' of 2, snare on 3, ghost note, soft hats."""
    t = a; step = bar / 8
    while t < b - 1e-6:
        pos = round((t % bar) / step); sw = swing if pos % 2 == 1 else 0.0
        if pos in (0, 3): mix.add(lofi_kick(), t + sw, 1.0 * g)
        if pos == 4: mix.add(snare(), t, 0.95 * g)
        if pos == 7: mix.add(snare(), t + sw, 0.22 * g)
        mix.add(soft_hat(1.0 if pos % 2 == 0 else 0.6), t + sw, 0.9 * g, pan=0.2)
        t += step


# ---------------- sound effects (sync these to on-screen events) ----------------
def whoosh(d=0.5, up=True, strength=1.0):
    """Filtered-noise sweep. Use 0.1 s BEFORE a transition or camera move."""
    t = t_(d)
    n = rng.standard_normal(len(t)); out = np.zeros_like(t); seg = 256
    for i in range(0, len(t), seg):
        p = i / len(t)
        fc = (400 + 5200 * p) if up else (5600 - 5200 * p)
        out[i:i + seg] = bp(n[max(0, i - 2048):i + seg], fc * 0.6, min(fc * 1.6, 20000))[-len(out[i:i + seg]):]
    return out * np.sin(np.pi * np.clip(t / d, 0, 1)) ** 1.6 * 0.55 * strength


def impact(d=1.4, strength=1.0):
    """Cinematic boom for word slams and scene cuts."""
    t = t_(d)
    f = 30 + 90 * np.exp(-t * 12)
    boom = np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t * 3.2)
    noise = lp(rng.standard_normal(len(t)), 1800) * np.exp(-t * 9) * 0.5
    crack = hp(rng.standard_normal(len(t)), 3000) * np.exp(-t * 60) * 0.35
    return np.tanh((boom + noise + crack) * 1.7) * 0.9 * strength


def riser(d=1.0):
    """Tension build before a reveal."""
    t = t_(d); p = t / d
    x = bp(rng.standard_normal(len(t)), 1500, 9000) * p ** 2 * 0.35
    f = 220 * 2 ** (p * 2.2)
    return x + np.sin(2 * np.pi * np.cumsum(f) / SR) * p ** 2.5 * 0.12


def pop(f=900, d=0.12):
    """Bubbly pop for badges, labels, chips appearing."""
    t = t_(d)
    ff = f * (1 + 1.2 * np.exp(-t * 60))
    return np.sin(2 * np.pi * np.cumsum(ff) / SR) * np.exp(-t * 38) * 0.5


def click(d=0.03):
    """UI tap / typing key."""
    t = t_(d)
    return hp(rng.standard_normal(len(t)), 2000) * np.exp(-t * 400) * 0.45 + np.sin(2 * np.pi * 2200 * t) * np.exp(-t * 300) * 0.2


def ding(f=1318.5, d=0.9):
    """Bright 'achievement' chime (E6 by default)."""
    t = t_(d)
    x = np.sin(2 * np.pi * f * t) + 0.45 * np.sin(2 * np.pi * f * 2.0 * t) + 0.2 * np.sin(2 * np.pi * f * 3.01 * t)
    return x * np.exp(-t * 4.5) * np.minimum(1, t / 0.002) * 0.22


def coin():
    """Two-note 'XP gained' sound."""
    a = ding(1975.5, 0.12) * 1.2; b = ding(2637.0, 0.6)
    out = np.zeros(int(0.07 * SR) + len(b)); out[:len(a)] += a; out[int(0.07 * SR):] += b
    return out


# ---------------- mixing ----------------
class Mix:
    """A stereo bus. add() places a sound at time t (seconds) with gain g and pan (-1 left .. 1 right)."""

    def __init__(self, dur):
        self.buf = np.zeros((2, int(dur * SR) + SR))

    def add(self, x, t, g=1.0, pan=0.0):
        x = np.asarray(x)
        if x.ndim == 1:
            x = np.stack([x * (1 - max(0, pan)), x * (1 + min(0, pan))])
        i = int(t * SR); n = min(x.shape[1], self.buf.shape[1] - i)
        if n > 0: self.buf[:, i:i + n] += x[:, :n] * g

    def duck(self, times, depth=0.28, d=0.18):
        """Sidechain feel: dip this bus briefly at each time (e.g. on every kick) so effects cut through."""
        env = np.ones(self.buf.shape[1])
        for tt in times:
            i = int(tt * SR); n = int(d * SR)
            if 0 <= i and i + n < len(env): env[i:i + n] = np.minimum(env[i:i + n], 1 - depth + depth * np.linspace(0, 1, n))
        self.buf *= env

    @staticmethod
    def blend(buses, dur):
        out = Mix(dur)
        for bus, g in buses: out.buf += bus.buf * g
        return out

    def master(self, dur, peak=0.89):
        """Soft saturation + normalize. peak 0.70 lands near -13 LUFS for these mixes (TikTok/Reels sweet spot)."""
        y = self.buf[:, :int(dur * SR)]
        y = np.tanh(y * 1.15) / np.tanh(1.15)
        y = y / (np.max(np.abs(y)) + 1e-9) * peak
        f = int(0.004 * SR); y[:, :f] *= np.linspace(0, 1, f)
        return y

    @staticmethod
    def save(y, path):
        d = (np.clip(y.T, -1, 1) * 32767).astype('<i2')
        with wave.open(path, 'wb') as w:
            w.setnchannels(2); w.setsampwidth(2); w.setframerate(SR); w.writeframes(d.tobytes())


